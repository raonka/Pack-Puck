#!/usr/bin/env python3
"""Pack Pucks — C4 link behaviour and disturbance observations.

Rescoped 2026-10-10 from "failure-mode taxonomy". The
matched session (22 Aug) is the subject; a short pilot-grade section
reports the only timeouts in the campaign record (13 Jul pilot, no
ground truth).

Per run (406.25 / 1625 kHz × static / stop-and-go), from the raw
Initiator CSVs (read-only):

  1. Outcome counts SUCCESS / TIMEOUT / ERROR, and the max
     consecutive_failures value.
  2. Every distinct radio_status_code, with counts.
  3. Implausible readings:
       - negative raw_distance_m;
       - readings more than 50 m from the marker truth.
     Reported in two scopes: (a) the post-discard marker windows used by
     every paper table; (b) all rows of the run's kept files. For (b),
     stop-and-go transit rows have no truth, so only the negative test
     applies there; static files have truth throughout.
     Operator-discarded retake files are reported separately and are
     not part of the run.
  4. Initiator RSSI validity per run. Where valid: Spearman rank
     correlation of RSSI with |reading − truth| over post-discard
     SUCCESS rows (per bandwidth, both tiers pooled; per run; and the
     median of the within-marker correlations), plus a per-marker median
     RSSI table.

Marker windows and the Methodology §7.2 discard come from
tools/per_marker_tables.py.

Output: data/analysis/c4_failure_modes.md

Usage:
    python tools/c4_failure_modes.py
"""

from __future__ import annotations

import json
import statistics
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import qc_session as qc            # noqa: E402  (parse_csv_file)
import per_marker_tables as pmt    # noqa: E402  (build, RUNS_D2, MARKERS)

OUT = Path("data/analysis/c4_failure_modes.md")
PILOT = Path("data/ranging_experiments/2026-07-13_ParadeGround_pilot/raw/"
             "20260713_073950-Initiator")
FAR_M = 50.0
INVALID_RSSI = {0, -150}   # TIMEOUT/ERROR convention; ranging-RSSI register zero point
RUNS = [("406.25", "static"), ("406.25", "stop-and-go"),
        ("1625", "static"), ("1625", "stop-and-go")]
PLAN_TIER = {"static": "static", "stop-and-go": "stop_and_go"}


def plan_files(cfg: dict, tier: str, reasons: bool = False):
    """(kept {file: truth or None}, discarded [file]) for one run; with
    reasons=True the second item is {file: (truth, reason)}."""
    plan = json.loads(cfg["plan"].read_text(encoding="utf-8"))
    run = next(r for r in plan["runs"] if r["run_id"] == PLAN_TIER[tier])
    kept, disc, why = {}, [], {}
    for name, v in run["files"].items():
        if isinstance(v, dict):
            if v.get("disposition") == "discarded":
                disc.append(name)
                why[name] = (v.get("true_m"), v.get("reason", ""))
                continue
            v = v.get("true_m")
        kept[name] = v
    return (kept, why) if reasons else (kept, disc)


def ranks(v: list[float]) -> list[float]:
    order = sorted(range(len(v)), key=lambda i: v[i])
    r = [0.0] * len(v)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and v[order[j + 1]] == v[order[i]]:
            j += 1
        avg = (i + j) / 2 + 1
        for k in range(i, j + 1):
            r[order[k]] = avg
        i = j + 1
    return r


def spearman(x: list[float], y: list[float]) -> float:
    rx, ry = ranks(x), ranks(y)
    mx, my = statistics.fmean(rx), statistics.fmean(ry)
    num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    den = (sum((a - mx) ** 2 for a in rx) * sum((b - my) ** 2 for b in ry)) ** 0.5
    return num / den if den else float("nan")


def main() -> int:
    windows = pmt.build(discard=True)
    L = ["# Pack Pucks — C4 link behaviour and disturbance observations "
         "(22 Aug 2026; pilot-grade timeouts from 13 Jul)", "",
         "Generated by `tools/c4_failure_modes.py`. Raw CSVs read-only. "
         "**Numbers only.**", "",
         "## Inputs", ""]
    for bw, cfg in pmt.RUNS_D2.items():
        L.append(f"- {bw} kHz: `{cfg['raw'].as_posix()}/`, plan "
                 f"`{cfg['plan'].as_posix()}`, laps `{cfg['laps'].as_posix()}`")
    L += [f"- Marker windows (post-discard): `tools/per_marker_tables.py` → "
          f"`{pmt.OUT_D2.as_posix()}`", "",
          "Scopes:",
          "- **(a) windows** = post-discard marker windows, the rows behind "
          "every per-marker table.",
          "- **(b) kept files** = every row of the run's kept files, "
          "including the first 5 s and, for stop-and-go, the walk "
          "transits.",
          "- **Retakes** = operator-discarded files, reported separately.",
          ""]

    # ---- 1-3: outcomes, codes, implausible ------------------------------
    L += ["## 1. Outcomes, status codes, consecutive failures", "",
          "| BW kHz | tier | scope | rows | SUCCESS | TIMEOUT | ERROR | "
          "radio_status_code values (count) | max consecutive_failures |",
          "|---|---|---|---|---|---|---|---|---|"]
    impl, rssi_info, totals, alltot = [], {}, Counter(), Counter()
    for bw, tier in RUNS:
        cfg = pmt.RUNS_D2[bw]
        kept, disc = plan_files(cfg, tier)
        for scope, names in (("(b) kept files", list(kept)),
                             ("retakes", disc)):
            rows = [r for n in names for r in qc.parse_csv_file(cfg["raw"] / n).rows]
            if not rows:
                continue
            st = Counter(r.status for r in rows)
            codes = Counter(r.radio_status_code for r in rows)
            cf = max(r.consecutive_failures for r in rows)
            L.append(f"| {bw} | {tier} | {scope} ({len(names)} file"
                     f"{'s' if len(names) != 1 else ''}) | {len(rows)} | "
                     f"{st['SUCCESS']} | {st['TIMEOUT']} | {st['ERROR']} | "
                     + ", ".join(f"{c} ({n})" for c, n in sorted(codes.items()))
                     + f" | {cf} |")
            alltot.update(st)
            if scope.startswith("(b)"):
                totals.update(st)
                # negatives anywhere in kept files (marker = file truth for
                # static, None for the single stop-and-go file); far readings
                # only where truth is defined (static files)
                neg, far_static = [], []
                for n, t in kept.items():
                    for r in qc.parse_csv_file(cfg["raw"] / n).rows:
                        if r.raw_distance_m < 0:
                            neg.append((t, r))
                        if (t is not None and r.status == "SUCCESS"
                                and abs(r.raw_distance_m - t) > FAR_M):
                            far_static.append((t, r))
                impl.append((bw, tier, "(b) kept files", neg, far_static))
                # RSSI validity on SUCCESS rows of kept files
                rs = [r.rssi_dbm for r in rows if r.status == "SUCCESS"]
                bad = sum(1 for x in rs if x in INVALID_RSSI)
                rssi_info[(bw, tier)] = (len(rs), bad, len(set(rs)),
                                         min(rs), max(rs))
        # scope (a)
        wn = windows[("22 Aug", bw, tier)]
        neg_a = [(m, r) for m, s in wn.items() for r in s["rows"]
                 if r.raw_distance_m < 0]
        far_a = [(m, r) for m, s in wn.items() for r in s["rows"]
                 if r.status == "SUCCESS" and abs(r.raw_distance_m - m) > FAR_M]
        impl.append((bw, tier, "(a) windows", neg_a, far_a))
    L += ["", f"Totals over kept files, all four runs: SUCCESS "
          f"{totals['SUCCESS']}, TIMEOUT {totals['TIMEOUT']}, ERROR "
          f"{totals['ERROR']}. Including the operator-discarded retakes: "
          f"{sum(alltot.values())} attempts, SUCCESS {alltot['SUCCESS']}, "
          f"TIMEOUT {alltot['TIMEOUT']}, ERROR {alltot['ERROR']}.", ""]

    L += ["## 2. Implausible readings", "",
          f"Negative = `raw_distance_m` < 0. Far = |reading − marker truth| "
          f"> {FAR_M:g} m (only where truth is defined).", "",
          "| BW kHz | tier | scope | negative (count) | negative at | far "
          "(count) | far at |", "|---|---|---|---|---|---|---|"]
    def at(pairs):
        return ", ".join(f"{m:g} m" for m in sorted({m for m, _ in pairs})) or "—"

    for bw, tier, scope, neg, far in impl:
        has_truth = scope.startswith("(a)") or tier == "static"
        if has_truth:
            n_at = at(neg)
        else:
            n_at = ("outside dwell windows (transit): "
                    + ", ".join(f"{r.raw_distance_m:.1f} m @ "
                                f"{r.timestamp_ms / 1000:.1f} s"
                                for _, r in neg)) if neg else "—"
        f_at = at(far) if has_truth else "n/a (no truth in transits)"
        far_n = len(far) if has_truth else "n/a"
        L.append(f"| {bw} | {tier} | {scope} | {len(neg)} | {n_at} | "
                 f"{far_n} | {f_at} |")
    L.append("")

    # ---- 4: RSSI ---------------------------------------------------------
    L += ["## 3. Initiator RSSI", "",
          "Validity test: SUCCESS rows whose `rssi_dbm` is not 0 (TIMEOUT/"
          "ERROR convention) or −150 (ranging-RSSI register read back 0), "
          "with more than one distinct value per run.", "",
          "| BW kHz | tier | SUCCESS rows (kept files) | invalid values | "
          "distinct values | range dBm | valid? |",
          "|---|---|---|---|---|---|---|"]
    valid = {}
    for k, (n, bad, nd, lo, hi) in rssi_info.items():
        ok = bad == 0 and nd > 1
        valid[k] = ok
        L.append(f"| {k[0]} | {k[1]} | {n} | {bad} | {nd} | {lo} to {hi} | "
                 f"{'yes' if ok else 'NO'} |")
    L += ["", "Responder RSSI is not covered here: it is constant −150 on the "
          "406.25 Responder log and absent for 1625 (22 Aug session log D8).",
          ""]

    L += ["### Spearman correlation, RSSI vs |error| (post-discard SUCCESS "
          "rows)", "",
          "|error| = |raw_distance_m − marker|. Both RSSI and marker distance "
          "change along the line, so the pooled coefficient mixes the "
          "distance trend with any within-marker relationship. The "
          "within-marker column holds distance fixed.", "",
          "| BW kHz | scope | n rows | Spearman ρ (pooled) | median "
          "within-marker ρ | within-marker ρ range |",
          "|---|---|---|---|---|---|"]
    for bw in ("406.25", "1625"):
        groups = [("both tiers pooled", ("static", "stop-and-go")),
                  ("static", ("static",)), ("stop-and-go", ("stop-and-go",))]
        for label, tiers in groups:
            if not all(valid[(bw, t)] for t in tiers):
                L.append(f"| {bw} | {label} | — | RSSI not valid | — | — |")
                continue
            xs, ys, within = [], [], []
            for t in tiers:
                for m, s in windows[("22 Aug", bw, t)].items():
                    succ = [r for r in s["rows"] if r.status == "SUCCESS"]
                    x = [r.rssi_dbm for r in succ]
                    y = [abs(r.raw_distance_m - m) for r in succ]
                    xs += x
                    ys += y
                    within.append(spearman(x, y))
            L.append(f"| {bw} | {label} | {len(xs)} | {spearman(xs, ys):+.2f} | "
                     f"{statistics.median(within):+.2f} | "
                     f"{min(within):+.2f} to {max(within):+.2f} |")
    L.append("")

    L += ["### Median initiator RSSI per marker (dBm, post-discard SUCCESS "
          "rows)", "",
          "| marker m | 406.25 static | 406.25 s&g | 1625 static | "
          "1625 s&g |", "|---|---|---|---|---|"]
    for m in pmt.MARKERS:
        cells = []
        for bw, tier in RUNS:
            s = windows[("22 Aug", bw, tier)][float(m)]
            cells.append(f"{s['rssi_median']:.0f}")
        L.append(f"| {m} | " + " | ".join(cells) + " |")
    L.append("")

    # ---- 4: operator retakes (disturbances), 22 Aug ----------------------
    L += ["## 4. Operator-discarded retakes (disturbances), 22 Aug", "",
          "Reasons are quoted verbatim from the operator-confirmed session "
          "plans (field notes). Retake and kept statistics both use the "
          "Methodology §7.2 first-5-s discard; N = post-discard attempts, "
          "all SUCCESS.", "",
          "| BW kHz | tier | marker m | retake file | reason (verbatim) | "
          "retake N | retake median m | retake IQR m | retake min–max m | "
          "kept median m | kept IQR m | kept min–max m |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for bw, tier in RUNS:
        cfg = pmt.RUNS_D2[bw]
        _, why = plan_files(cfg, tier, reasons=True)
        for name, (truth, reason) in why.items():
            rows = qc.parse_csv_file(cfg["raw"] / name).rows
            r = reason.replace("|", "/")
            if truth is None:
                st = Counter(x.status for x in rows)
                L.append(f"| {bw} | {tier} | 300→ (partial run) | `{name}` | "
                         f"{r} | {len(rows)} rows, {st['SUCCESS']} SUCCESS "
                         "(whole file) | — | — | "
                         f"{min(x.raw_distance_m for x in rows):.1f}–"
                         f"{max(x.raw_distance_m for x in rows):.1f} | — | — | — |")
                continue
            ret = pmt.window_stats(rows, float(truth), True)
            kept = windows[("22 Aug", bw, tier)][float(truth)]
            L.append(f"| {bw} | {tier} | {truth:g} | `{name}` | {r} | "
                     f"{ret['N']} | {ret['median']:.1f} | {ret['iqr']:.1f} | "
                     f"{ret['min']:.1f}–{ret['max']:.1f} | {kept['median']:.1f} | "
                     f"{kept['iqr']:.1f} | {kept['min']:.1f}–{kept['max']:.1f} |")
    L.append("")

    # ---- 5: pilot timeouts (pilot-grade) -------------------------------
    L += ["## 5. Pilot outing timeouts (2026-07-13, pilot-grade)", "",
          f"`{PILOT.as_posix()}/`: 1625 kHz / SF8, positions paced, **no "
          "surveyed ground truth**; reported for link behaviour only. "
          "Cycle length = timestamp of the row minus timestamp of the "
          "previous row.", "",
          "| file | rows | SUCCESS | TIMEOUT | ERROR | status codes (count) | "
          "TIMEOUT cycle lengths s | median SUCCESS cycle ms |",
          "|---|---|---|---|---|---|---|---|"]
    ptot = Counter()
    tall = []
    for f in sorted(PILOT.glob("pucklog_*.csv"),
                    key=lambda q: int(q.stem.rsplit("_", 1)[1])):
        rows = qc.parse_csv_file(f).rows
        st = Counter(x.status for x in rows)
        ptot.update(st)
        codes = Counter(x.radio_status_code for x in rows)
        tlen = [(rows[i].timestamp_ms - rows[i - 1].timestamp_ms) / 1000
                for i in range(1, len(rows)) if rows[i].status == "TIMEOUT"]
        tall += tlen
        slen = [rows[i].timestamp_ms - rows[i - 1].timestamp_ms
                for i in range(1, len(rows))
                if rows[i].status == "SUCCESS" and rows[i - 1].status == "SUCCESS"]
        L.append(f"| `{f.name}` | {len(rows)} | {st['SUCCESS']} | "
                 f"{st['TIMEOUT']} | {st['ERROR']} | "
                 + ", ".join(f"{c} ({n})" for c, n in sorted(codes.items()))
                 + f" | {', '.join(f'{t:.1f}' for t in tlen) or '—'} | "
                 f"{statistics.median(slen):.0f} |")
    L += ["", f"Pilot totals: {sum(ptot.values())} attempts; SUCCESS "
          f"{ptot['SUCCESS']}, TIMEOUT {ptot['TIMEOUT']}, ERROR "
          f"{ptot['ERROR']}. Every TIMEOUT row carries status code −901 "
          "(RadioLib ranging timeout). TIMEOUT cycle lengths "
          f"{min(tall):.1f}–{max(tall):.1f} s.", ""]

    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
