#!/usr/bin/env python3
"""Pack Pucks — dwell length per marker, 22 Aug 2026 matched session.

For every marker of every 22 Aug run (406.25 / 1625 kHz × static /
stop-and-go), computes the dwell length before and after the Methodology
§7.2 first-5-s discard, from the raw CSV timestamps and the same windows
used for every per-marker table (tools/per_marker_tables.py: session plans
for the static files, operator lap-log windows for stop-and-go).

Definitions:
  static, pre-discard        last minus first logged-row timestamp of the file
  stop-and-go, pre-discard   lap-window length (lap end minus lap start, file
                             axis; the measured dwell of the operator log)
  post-discard (both tiers)  last minus first timestamp of the rows kept
                             after the discard

Raw CSVs are read-only. Output: data/analysis/dwell_table.md

Usage:
    python tools/dwell_table.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import per_marker_tables as pmt   # noqa: E402  (build, RUNS_D2, MARKERS, OUT_D2)

OUT = Path("data/analysis/dwell_table.md")
RUNS = [("406.25", "static"), ("406.25", "stop-and-go"),
        ("1625", "static"), ("1625", "stop-and-go")]


def span_s(rows) -> float:
    return (rows[-1].timestamp_ms - rows[0].timestamp_ms) / 1000


def main() -> int:
    pre = pmt.build(discard=False)
    post = pmt.build(discard=True)
    table = {}
    for bw, tier in RUNS:
        key = ("22 Aug", bw, tier)
        per = {}
        for m in sorted(pre[key]):
            a, b = pre[key][m], post[key][m]
            if tier == "static":
                d_pre = span_s(a["rows"])
            else:
                w0, w1 = a["window"]
                d_pre = w1 - w0
            per[m] = {"file": a["file"], "pre": d_pre, "post": span_s(b["rows"]),
                      "n_pre": a["N"], "n_post": b["N"]}
        table[(bw, tier)] = per

    L = ["# Pack Pucks — Dwell length per marker (22 Aug 2026)", "",
         "Generated by `tools/dwell_table.py` from the raw CSV timestamps "
         "(read-only). **Numbers only.**", "",
         "## Inputs", ""]
    for cfg in pmt.RUNS_D2.values():
        L += [f"- `{cfg['raw'].as_posix()}/`", f"- `{cfg['plan'].as_posix()}`",
              f"- `{cfg['laps'].as_posix()}`"]
    L += ["- Windows and discard: `tools/per_marker_tables.py` (the same "
          f"windows as `{pmt.OUT_D2.as_posix()}`).", "",
          "## Definitions", "",
          "- **Static, pre-discard:** last minus first logged-row "
          "timestamp of the marker's file.",
          "- **Stop-and-go, pre-discard:** lap-window length (lap end minus "
          "lap start on the file's time axis) from the operator lap log.",
          "- **Post-discard, both tiers:** last minus first timestamp of the "
          "rows kept after the Methodology §7.2 first-5-s discard.",
          "- **N:** attempts in the window, before and after the discard.", "",
          "## Summary per run (s)", "",
          "| BW kHz | tier | pre-discard min–max | post-discard min–max |",
          "|---|---|---|---|"]
    for (bw, tier), per in table.items():
        pr = [x["pre"] for x in per.values()]
        po = [x["post"] for x in per.values()]
        L.append(f"| {bw} | {tier} | {min(pr):.1f}–{max(pr):.1f} | "
                 f"{min(po):.1f}–{max(po):.1f} |")
    L.append("")
    for (bw, tier), per in table.items():
        L += [f"## {bw} kHz — {tier}", "",
              "| marker m | file | dwell pre-discard s | dwell post-discard s | "
              "N pre | N post |", "|---|---|---|---|---|---|"]
        for m, x in per.items():
            L.append(f"| {m:g} | `{x['file']}` | {x['pre']:.1f} | "
                     f"{x['post']:.1f} | {x['n_pre']} | {x['n_post']} |")
        L.append("")
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
