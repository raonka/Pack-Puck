#!/usr/bin/env python3
"""Pack Pucks — C3 post-hoc filter characterisation (22 Aug matched session).

For every marker window of the 22 Aug session (both bandwidths, both
tiers), the SUCCESS readings are sorted by time and passed through a
sliding window of three consecutive readings:

  raw          the readings themselves (N outputs)
  median-of-3  median of each full window of 3 (N - 2 outputs)
  max-of-3     maximum of each full window of 3 (N - 2 outputs)

Only full windows are used: no edge padding. Each filter's output is
summarised exactly like the raw tables: median, signed error
(median − marker), IQR (Q3 − Q1, linear interpolation), N outputs.

Windows and the Methodology §7.2 first-5-s discard come from
tools/per_marker_tables.py (the same rows as
data/analysis/2026-08-22_GMATownship_day2_tables_discard5s.md).
Raw CSVs are read-only. Filters are applied in analysis only.

This characterises where each filter changes bias
and spread. It does not rank the filters.

Output: data/analysis/c3_filters.md

Usage:
    python tools/c3_filters.py
"""

from __future__ import annotations

import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import qc_session as qc            # noqa: E402  (q1_q3)
import per_marker_tables as pmt    # noqa: E402  (build, MARKERS, input paths)

OUT = Path("data/analysis/c3_filters.md")
EMAX3 = 0.846      # expected maximum of 3 iid standard normals (order statistic)
TOL = 0.40         # pass band: observed shift within +/-40 % of predicted
FILTERS = ("raw", "median-of-3", "max-of-3")
RUNS = [("406.25", "static"), ("406.25", "stop-and-go"),
        ("1625", "static"), ("1625", "stop-and-go")]


def apply(name: str, v: list[float]) -> list[float]:
    if name == "raw":
        return list(v)
    f = statistics.median if name == "median-of-3" else max
    return [f(v[i:i + 3]) for i in range(len(v) - 2)]


def summarise(out: list[float], truth: float) -> dict:
    q1, q3 = qc.q1_q3(out)
    med = statistics.median(out)
    return {"median": med, "err": med - truth, "iqr": q3 - q1, "N": len(out)}


def compute() -> dict:
    """{(bw, tier): {marker: {filter: summary}}}"""
    res = pmt.build(discard=True)
    out = {}
    for bw, tier in RUNS:
        per = {}
        for m, st in res[("22 Aug", bw, tier)].items():
            succ = sorted((r for r in st["rows"] if r.status == "SUCCESS"),
                          key=lambda r: r.timestamp_ms)
            v = [r.raw_distance_m for r in succ]
            per[m] = {f: summarise(apply(f, v), m) for f in FILTERS}
            per[m]["sigma"] = statistics.stdev(v)
            # the raw path must reproduce the published post-discard table
            assert f"{per[m]['raw']['median']:.1f}" == f"{st['median']:.1f}"
            assert f"{per[m]['raw']['iqr']:.1f}" == f"{st['iqr']:.1f}"
        out[(bw, tier)] = per
    return out


def mean(v):
    return sum(v) / len(v)


def aggregates(per: dict) -> dict:
    a = {}
    for f in FILTERS:
        e = [per[m][f]["err"] for m in per]
        a[f] = {"mae": mean([abs(x) for x in e]), "bias": mean(e),
                "iqr": mean([per[m][f]["iqr"] for m in per])}
    return a


def describe(bw: str, tier: str, per: dict, agg: dict) -> list[str]:
    """Factual description of how each filter moves bias and spread
    relative to raw. No ranking."""
    L = []
    for f in FILTERS[1:]:
        db = [per[m][f]["err"] - per[m]["raw"]["err"] for m in per]
        di = [per[m][f]["iqr"] - per[m]["raw"]["iqr"] for m in per]
        up = sum(1 for x in db if x > 0.05)
        dn = sum(1 for x in db if x < -0.05)
        nar = sum(1 for x in di if x < -0.05)
        wid = sum(1 for x in di if x > 0.05)
        L.append(
            f"- **{f}** vs raw. *Bias:* signed error moves by "
            f"{min(db):+.2f} to {max(db):+.2f} m per marker (higher at {up}, "
            f"lower at {dn}, within ±0.05 m at {10 - up - dn} of 10 markers); "
            f"mean signed bias {agg['raw']['bias']:+.2f} → "
            f"{agg[f]['bias']:+.2f} m. *Spread:* IQR moves by {min(di):+.2f} "
            f"to {max(di):+.2f} m (narrower at {nar}, wider at {wid}, within "
            f"±0.05 m at {10 - nar - wid}); mean IQR {agg['raw']['iqr']:.2f} → "
            f"{agg[f]['iqr']:.2f} m.")
    return L


def main() -> int:
    data = compute()
    L = ["# Pack Pucks — C3 post-hoc filter characterisation (22 Aug 2026)", "",
         "Generated by `tools/c3_filters.py`. **Numbers and descriptions "
         "only; no filter is ranked or recommended**.", "",
         "## Inputs and method", "",
         f"- Windows and discard: `tools/per_marker_tables.py`, i.e. the rows "
         f"behind `{pmt.OUT_D2.as_posix()}` (Methodology §7.2 first-5-s "
         "discard; stop-and-go = lap-log dwell windows).",
         "- Raw CSVs: " + ", ".join(
             f"`{c['raw'].as_posix()}/`" for c in pmt.RUNS_D2.values()) + ".",
         "- **Filters.** SUCCESS readings in time order; sliding window of "
         "3 consecutive readings, full windows only (no padding). Raw = "
         "N outputs; median-of-3 and max-of-3 = N − 2 outputs.",
         "- **Per-marker summary** of each filter's output: median, signed "
         "error = median − marker, IQR (Q3 − Q1, linear interpolation), "
         "N = number of outputs.",
         "- **Aggregates** are unweighted means over the ten markers: MAE = "
         "mean |error|, mean signed bias, mean IQR. They are computed from "
         "unrounded values, so they can differ in the last digit from "
         "aggregates computed on the 0.1 m-rounded tables "
         "(`aggregates.md`).",
         "- The raw path reproduces the post-discard tables' median and IQR "
         "at every marker (asserted by the script).",
         "- Ground truth: ±0.5 m at 300 m (Methodology §5.3); cone-position "
         "error is common to every filter and both bandwidths.", ""]

    L += ["## Aggregates per bandwidth × tier", "",
          "| BW kHz | tier | filter | MAE m | mean signed bias m | "
          "mean IQR m |", "|---|---|---|---|---|---|"]
    aggs = {}
    for k, per in data.items():
        aggs[k] = aggregates(per)
        for f in FILTERS:
            a = aggs[k][f]
            L.append(f"| {k[0]} | {k[1]} | {f} | {a['mae']:.2f} | "
                     f"{a['bias']:+.2f} | {a['iqr']:.2f} |")

    L += ["", "## Where each filter changes bias and spread (relative to "
          "raw)", "",
          "Δ = filter − raw, per marker. Thresholds of ±0.05 m are used only "
          "to count markers.", ""]
    for k, per in data.items():
        L += [f"### {k[0]} kHz — {k[1]}", ""]
        L += describe(k[0], k[1], per, aggs[k])
        L.append("")

    # ---- order-statistic sanity check for max-of-3 ----------------------
    L += ["## Order-statistic check for max-of-3", "",
          f"For three independent normal readings with standard deviation σ, "
          f"the expected maximum lies {EMAX3} σ above the mean. Predicted "
          f"shift = {EMAX3} × σ, where σ = sample standard deviation of the "
          "post-discard raw readings at that marker. Observed shift = "
          "max-of-3 median − raw median. σ is used for this check only; it "
          "is not a reported statistic (the paper reports median and IQR). "
          f"Pass band: observed run mean within ±{TOL:.0%} of predicted run "
          "mean. (For the *median* of the max, the normal-theory factor is "
          "0.82 rather than 0.846; the pass band covers the difference.)", "",
          "| BW kHz | tier | mean σ m | mean predicted shift m | mean observed "
          "shift m | observed / predicted | per-marker ratio range | within "
          f"±{TOL:.0%}? |", "|---|---|---|---|---|---|---|---|"]
    a4_pass = True
    for k, per in data.items():
        pred = [EMAX3 * per[m]["sigma"] for m in per]
        obs = [per[m]["max-of-3"]["median"] - per[m]["raw"]["median"]
               for m in per]
        ratios = [o / pr for o, pr in zip(obs, pred)]
        r = mean(obs) / mean(pred)
        ok = abs(r - 1) <= TOL
        a4_pass &= ok
        L.append(f"| {k[0]} | {k[1]} | {mean([per[m]['sigma'] for m in per]):.2f} "
                 f"| {mean(pred):.2f} | {mean(obs):.2f} | {r:.2f} | "
                 f"{min(ratios):.2f}–{max(ratios):.2f} | "
                 f"{'yes' if ok else 'NO'} |")
    L += ["", f"**Result: {'PASS' if a4_pass else 'FAIL'}** — the observed "
          "max-of-3 shift is " + ("within" if a4_pass else "NOT within")
          + f" ±{TOL:.0%} of the order-statistic prediction in every run.", ""]

    L += ["## Per-marker results", ""]
    for k, per in data.items():
        L += [f"### {k[0]} kHz — {k[1]}", "",
              "| marker m | raw median | raw err | raw IQR | raw N | "
              "med3 median | med3 err | med3 IQR | med3 N | "
              "max3 median | max3 err | max3 IQR | max3 N |",
              "|" + "---|" * 13]
        for m in sorted(per):
            row = f"| {m:g} |"
            for f in FILTERS:
                x = per[m][f]
                row += (f" {x['median']:.1f} | {x['err']:+.1f} | "
                        f"{x['iqr']:.1f} | {x['N']} |")
            L.append(row)
        L.append("")

    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT}")
    for k in data:
        a = aggs[k]
        print(k, " | ".join(f"{f}: MAE {a[f]['mae']:.2f} bias {a[f]['bias']:+.2f}"
                            f" IQR {a[f]['iqr']:.2f}" for f in FILTERS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
