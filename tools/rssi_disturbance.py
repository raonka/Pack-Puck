#!/usr/bin/env python3
"""Pack Pucks — Initiator RSSI on the disturbed files of 22 Aug.

Added 2026-10-25: tests whether Initiator RSSI separates the files the operator
recorded as disturbed from clean files at the same marker and bandwidth.

Files (406.25 kHz, the only bandwidth with operator retakes):
  - each operator-discarded static retake, and the kept file that
    replaced it (120, 150, 240, 300 m);
  - the kept 180 m static file with the 19.7 m rolling-median drift
    (QC HOLD; field note "180m - few people walked by"), against the
    lap-confirmed 180 m dwell of the 406.25 kHz stop-and-go run (same
    marker, same bandwidth, no annotation) as the clean reference;
  - the rejected first stop-and-go run (pucklog_D4DB1C_15.csv), whole
    file only: it has no arrival log, so no marker window or |error|.

Per file, on post-discard SUCCESS rows (Methodology §7.2 first-5-s
discard, as every paper table): median and IQR of rssi_dbm (linear
interpolation, as qc_session.py), and the within-file Spearman rank
correlation of rssi_dbm with |raw_distance_m - marker|.

Separation, per disturbed / clean pair: the difference of median RSSI
(disturbed minus clean, dB) and whether the disturbed median lies
outside the clean file's RSSI interquartile range.

Raw CSVs are opened read-only. Output: data/analysis/rssi_disturbance.md

Usage:
    python tools/rssi_disturbance.py
"""

from __future__ import annotations

import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import qc_session as qc            # noqa: E402  (parse_csv_file, q1_q3)
import per_marker_tables as pmt    # noqa: E402  (RUNS_D2, window_stats, build)
import c4_failure_modes as c4      # noqa: E402  (plan_files, spearman)

OUT = Path("data/analysis/rssi_disturbance.md")
BW = "406.25"
CFG = pmt.RUNS_D2[BW]
DRIFT_FILE = "pucklog_D4DB1C_8.csv"   # QC406S Verdict HOLD; S2 D5
REJECTED_SNG = "pucklog_D4DB1C_15.csv"  # S2 file dispositions


def file_stats(rows: list, truth: float | None) -> dict:
    succ = [r for r in rows if r.status == "SUCCESS"]
    rs = [r.rssi_dbm for r in succ]
    q1, q3 = qc.q1_q3(rs)
    out = {"n": len(succ), "median": statistics.median(rs), "q1": q1,
           "q3": q3, "iqr": q3 - q1, "min": min(rs), "max": max(rs)}
    if truth is not None:
        out["rho"] = c4.spearman(rs, [abs(r.raw_distance_m - truth) for r in succ])
    return out


def static_file(name: str, truth: float) -> dict:
    rows = qc.parse_csv_file(CFG["raw"] / name).rows
    rows = pmt.window_stats(rows, truth, discard=True)["rows"]
    return file_stats(rows, truth)


def main() -> int:
    kept, why = c4.plan_files(CFG, "static", reasons=True)
    by_truth = {float(t): n for n, t in kept.items() if t is not None}
    windows = pmt.build(discard=True)
    pairs = []
    for name, (truth, reason) in sorted(why.items(), key=lambda kv: kv[1][0]):
        truth = float(truth)
        pairs.append((f"{truth:g} m retake", name, reason,
                      static_file(name, truth),
                      f"kept replacement", by_truth[truth],
                      static_file(by_truth[truth], truth)))
    sng = windows[("22 Aug", BW, "stop-and-go")][180.0]
    pairs.append(("180 m drift file (kept, no retake)", DRIFT_FILE,
                  "QC HOLD, rolling-median drift 19.7 m; field note "
                  "'180m - few people walked by'",
                  static_file(DRIFT_FILE, 180.0),
                  "clean reference: stop-and-go 180 m dwell",
                  f"{sng['file']} {sng['window'][0]:.1f}-{sng['window'][1]:.1f} s",
                  file_stats(sng["rows"], 180.0)))
    rej = file_stats(qc.parse_csv_file(CFG["raw"] / REJECTED_SNG).rows, None)

    L = ["# Pack Pucks — Initiator RSSI on the disturbed files (22 Aug 2026, "
         "406.25 kHz)", "",
         "Generated by `tools/rssi_disturbance.py`. Raw CSVs read-only. "
         "**Numbers only.**", "",
         f"Inputs: `{CFG['raw'].as_posix()}/`, plan `{CFG['plan'].as_posix()}` "
         f"(retake reasons verbatim), laps `{CFG['laps'].as_posix()}`. Rows: "
         "post-discard SUCCESS rows (Methodology §7.2 first-5-s discard). "
         "RSSI quartiles by linear interpolation. ρ = within-file Spearman "
         "rank correlation of RSSI with |reading − marker|. Every row of "
         "these files is SUCCESS with status code 0 "
         "(`c4_failure_modes.md` §1).", "",
         "## 1. Per file", "",
         "| marker | role | file | reason / note | N | median RSSI dBm | "
         "RSSI IQR dB (Q1 to Q3) | RSSI min to max dBm | ρ(RSSI, \\|error\\|) |",
         "|---|---|---|---|---|---|---|---|---|"]

    def row(label, role, name, note, s):
        rho = f"{s['rho']:+.2f}" if "rho" in s else "n/a"
        return (f"| {label} | {role} | `{name}` | {note} | {s['n']} | "
                f"{s['median']:.1f} | {s['iqr']:.1f} ({s['q1']:.1f} to "
                f"{s['q3']:.1f}) | {s['min']} to {s['max']} | {rho} |")

    for label, dn, reason, ds, crole, cn, cs in pairs:
        L.append(row(label.split(" ")[0] + " m" if "retake" in label else "180 m",
                     "disturbed" if "retake" in label else "disturbed (kept)",
                     dn, reason, ds))
        L.append(row(label.split(" ")[0] + " m" if "retake" in label else "180 m",
                     crole, cn, "—", cs))
    L += ["",
          "## 2. Separation, disturbed vs clean", "",
          "| pair | Δ median RSSI, disturbed − clean (dB) | disturbed median "
          "outside clean IQR? | ρ disturbed | ρ clean |",
          "|---|---|---|---|---|"]
    n_out = 0
    for label, dn, reason, ds, crole, cn, cs in pairs:
        outside = not (cs["q1"] <= ds["median"] <= cs["q3"])
        n_out += outside
        L.append(f"| {label} | {ds['median'] - cs['median']:+.1f} | "
                 f"{'yes' if outside else 'no'} | {ds['rho']:+.2f} | "
                 f"{cs['rho']:+.2f} |")
    L += ["", f"Pairs with the disturbed median outside the clean IQR: "
          f"{n_out} of {len(pairs)}.", "",
          "## 3. Rejected first stop-and-go run (whole file)", "",
          f"`{REJECTED_SNG}`: no arrival log, so no marker window and no "
          f"|error|; whole file, all {rej['n']} SUCCESS rows, no discard "
          f"applied. Median RSSI {rej['median']:.1f} dBm, IQR {rej['iqr']:.1f} "
          f"dB ({rej['q1']:.1f} to {rej['q3']:.1f}), range {rej['min']} to "
          f"{rej['max']} dBm. Not compared with the kept run: the two files "
          "cover different distance spans (`c4_failure_modes.md` §4).", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
