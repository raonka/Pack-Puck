#!/usr/bin/env python3
"""Pack Pucks — LaTeX tables for the Part 1 paper, generated from data/analysis/.

Reads values as text from the analysis outputs and writes them into LaTeX
tables without recomputing or reformatting any number (only the sign is
wrapped in math mode). After writing, every value is read back from the
generated file and compared with its source; a mismatch aborts.

Outputs (paper/tables/):
  per_marker.tex  per-marker signed error, IQR, post-discard N and median
                  initiator RSSI for the four 22 Aug runs
                  <- data/analysis/2026-08-22_GMATownship_day2_tables_discard5s.md
                     TABLE 1
  matched.tex     Table I: MAE and mean signed error with 95 % bootstrap
                  intervals, the paired MAE ratio with its interval, and mean
                  IQR <- data/analysis/uncertainty.md section 1 and
                  data/analysis/aggregates.md "Accuracy and precision"
                  (added 2026-10-25)
  filters.tex     post-hoc filters: mean signed error and mean IQR per
                  bandwidth x tier for raw, median-of-3 and max-of-3
                  <- data/analysis/c3_filters.md "Aggregates per bandwidth x
                  tier" (added 2026-11-08; previously hand-written in main.tex)

cycle.tex (cycle time per bandwidth) was retired 2026-11-08: its values are
now text in Section V-C. fit.tex (least-squares signed error vs distance,
406.25 kHz) was retired 2026-11-10: the Discussion (D2) states the conclusion
from data/analysis/uncertainty.md section 2. siunitx S columns (per_marker,
filters) need \\usepackage{siunitx} in main.tex.

Usage:
    python tools/make_latex_tables.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

AN = Path("data/analysis")
T5 = AN / "2026-08-22_GMATownship_day2_tables_discard5s.md"
AGG = AN / "aggregates.md"
UNC = AN / "uncertainty.md"
FLT = AN / "c3_filters.md"
OUT = Path("paper/tables")

RUNS = ["406.25 kHz static", "406.25 kHz stop-and-go",
        "1625 kHz static", "1625 kHz stop-and-go"]
# Display labels: the hand-held tier is recorded with the stop-and-go
# procedure; the paper calls it the hand-held tier, and the source files
# keep their own labels.
TIER_LABEL = {"static": "static", "stop-and-go": "hand-held", "s&g": "hand-held"}


def cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def section(text: str, start: str) -> str:
    return text.split(start, 1)[1].split("\n## ", 1)[0]


def ms(v: str) -> str:
    """Sign only in math mode, so the digits stay in the text font like the
    unsigned cells; the digits are copied unchanged. Used in bracketed
    intervals, which siunitx S columns cannot hold."""
    return f"${v[0]}${v[1:]}" if v[:1] in "+-" else v




def per_marker() -> tuple[str, dict]:
    rows = [cells(l) for l in section(T5.read_text(encoding="utf-8"),
                                       "## TABLE 1").splitlines()
            if re.match(r"\|\s*\d+\s*\|", l)]
    # TABLE 1 columns per run: med, IQR, err, N, RSSI (5 each, after marker)
    src = {}
    L = [r"% GENERATED by tools/make_latex_tables.py from",
         f"%   {T5.as_posix()} TABLE 1. Do not edit by hand.",
         r"\begin{table*}[t]", r"\centering",
         # 2026-11-08 (figures and tables pass): units moved from the caption to
         # a header row; siunitx S columns align on the decimal point; natural
         # size at \footnotesize (the \resizebox scaled the table up).
         r"\caption{Per-marker results, 22 August 2026: signed error $e_k$ and "
         r"IQR of the post-discard successful readings, post-discard attempts "
         r"$N_k$, and median Initiator RSSI.}",
         r"\label{tab:per-marker}",
         r"\footnotesize\setlength{\tabcolsep}{3.5pt}",
         r"\sisetup{retain-explicit-plus}",
         r"\begin{tabular}{@{}r"
         + r"S[table-format=+2.1]S[table-format=1.1]S[table-format=3.0]"
           r"S[table-format=-2.0]" * 4 + "@{}}",
         r"\toprule",
         " & " + " & ".join(
             rf"\multicolumn{{4}}{{c}}"
             rf"{{{r.replace('stop-and-go', TIER_LABEL['stop-and-go']).replace(' kHz', chr(92) + ',kHz')}}}"
             for r in RUNS)
         + r" \\",
         " ".join(rf"\cmidrule(lr){{{2 + 4 * i}-{5 + 4 * i}}}" for i in range(4)),
         "Marker & " + " & ".join([r"{$e_k$} & {IQR} & {$N_k$} & {RSSI}"] * 4)
         + r" \\",
         "(m) & " + " & ".join([r"{(m)} & {(m)} & & {(dBm)}"] * 4) + r" \\",
         r"\midrule"]
    for c in rows:
        vals = []
        for i in range(4):
            med, iqr, err, n, rssi = c[1 + 5 * i: 6 + 5 * i]
            vals += [err, iqr, n, rssi]
            src[(c[0], RUNS[i])] = (err, iqr, n, rssi)
        # S columns take the numbers as plain text; siunitx sets the signs.
        L.append(c[0] + " & " + " & ".join(vals) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(L), src


# fit() (Table tab:fit) retired 2026-11-10 (Limitations pass): the Discussion (D2) states the
# conclusion (slope intervals include zero in all four fits; the 270 m spans of the
# two all-ten fits), sourced there to data/analysis/uncertainty.md section 2.


def matched() -> tuple[str, dict]:
    """Table I. MAE / mean signed error and their intervals from UNC
    section 1, point values cross-checked against AGG; mean IQR from AGG."""
    unc = UNC.read_text(encoding="utf-8")
    agg = AGG.read_text(encoding="utf-8")
    boot = {}
    for c in (cells(l) for l in section(unc, "## 1. Bootstrap").splitlines()
              if l.startswith("| static |") or l.startswith("| stop-and-go |")):
        if len(c) == 5:
            boot[(c[0], c[1], c[2])] = (c[3], *c[4].split(" to "))
        else:
            boot[(c[0], "ratio")] = (c[1].rstrip("×"),
                                     *(x.rstrip("×") for x in c[2].split(" to ")))

    def aggv(label: str, tier: str) -> str:
        line = next(l for l in agg.splitlines()
                    if l.startswith(f"| {label} | {tier} |"))
        return cells(line)[2].replace(" m", "").replace("×", "")

    tiers = (("static", "static", "Static"), ("stop-and-go", "s&g", "Hand-held"))
    bws = ("406.25 kHz", "1625 kHz")
    cols = [(t, bw) for t in tiers for bw in bws]  # Static 406, 1625; Hand-held 406, 1625
    src = {}
    mae, bias, iqr, ratio = {}, {}, {}, {}
    for utier, atier, _ in tiers:
        for bw in bws:
            mae[(utier, bw)] = boot[(utier, "MAE", bw)]
            bias[(utier, bw)] = boot[(utier, "mean signed error", bw)]
            iqr[(utier, bw)] = aggv(f"Mean IQR, {bw}", atier)
            for name, got, want in (("MAE", mae[(utier, bw)][0],
                                     aggv(f"MAE, {bw}", atier)),
                                    ("bias", bias[(utier, bw)][0],
                                     aggv(f"Signed bias, {bw}", atier))):
                if got != want:
                    sys.exit(f"error: matched {utier} {bw} {name}: {got} in "
                             f"UNC, {want} in AGG")
            src[(utier, bw)] = (*mae[(utier, bw)], *bias[(utier, bw)],
                                iqr[(utier, bw)])
        r = boot[(utier, "ratio")]
        if r[0] != aggv("MAE ratio 406.25 / 1625", atier):
            sys.exit(f"error: matched {utier} ratio: {r[0]} in UNC")
        src[(utier, "ratio")] = r
        ratio[utier] = r

    def row(label: str, vals: list[str]) -> str:
        return f"{label} & " + " & ".join(vals) + r" \\"

    def ivrow(d: dict, signed: bool, label: str = "") -> str:
        f = ms if signed else (lambda v: v)
        return row(label, [rf"\scriptsize [{f(d[(t[0], bw)][1])}, "
                           rf"{f(d[(t[0], bw)][2])}]" for t, bw in cols])

    bwtex = [bw.replace(" kHz", r"\,kHz") for _, bw in cols]
    L = [r"% GENERATED by tools/make_latex_tables.py from",
         f"%   {UNC.as_posix()} section 1 (MAE, mean signed error, MAE ratio, "
         "95 % bootstrap intervals) and",
         f"%   {AGG.as_posix()} \"Accuracy and precision\" (mean IQR; point "
         "values cross-checked). Do not edit by hand.",
         r"\begin{table}[t]", r"\centering",
         # 2026-11-08 (figures and tables pass): caption cut to two lines; units
         # moved to the row labels; "paired by marker" moved to the V-A text.
         r"\caption{Accuracy and precision by bandwidth and tier, means over "
         r"ten markers (22 August 2026). Brackets: 95\,\% bootstrap "
         r"interval.}",
         r"\label{tab:matched}",
         # 3pt and the two-line "Mean signed / error" label keep the table
         # inside \columnwidth unscaled (4pt and a one-line label: 19.8pt over).
         r"\footnotesize\setlength{\tabcolsep}{3pt}",
         r"\begin{tabular}{@{}lcccc@{}}", r"\toprule",
         r" & \multicolumn{2}{c}{Static} & \multicolumn{2}{c}{Hand-held} \\",
         r"\cmidrule(lr){2-3} \cmidrule(lr){4-5}",
         row("", bwtex), r"\midrule",
         row("MAE (m)", [mae[(t[0], bw)][0] for t, bw in cols]),
         ivrow(mae, signed=False) + "[2pt]",
         row("Mean signed", [ms(bias[(t[0], bw)][0]) for t, bw in cols]),
         ivrow(bias, signed=True, label="error (m)") + "[2pt]",
         row("Mean IQR (m)", [iqr[(t[0], bw)] for t, bw in cols]) + "[2pt]",
         row("MAE ratio", [rf"\multicolumn{{2}}{{c}}{{{ratio[t[0]][0]}$\times$ "
                           rf"[{ratio[t[0]][1]}, {ratio[t[0]][2]}]}}"
                           for t in tiers]),
         r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(L), src


# cycle() (Table tab:cycle) retired 2026-11-08 (figures and tables pass): the
# cycle-time medians, p05 / p95 and interval counts are now one pair of sentences
# in Section V-C, sourced there to AGG rows "Cycle time, <bw> kHz (pooled median,
# ...)" and "Cycle time p05 / p95, <bw> kHz".


def filters() -> tuple[str, dict]:
    """Post-hoc filter: mean signed error and mean IQR per bandwidth x tier for
    raw and median-of-3 <- FLT "Aggregates per bandwidth x tier".
    Hand-written in main.tex until 2026-11-08. 2026-11-10 (review edits): the
    max-of-3 column is retired (the filter is removed from the paper); FLT still
    holds its rows, which are ignored here."""
    sec = section(FLT.read_text(encoding="utf-8"), "## Aggregates per bandwidth")
    lines = [l for l in sec.splitlines() if l.startswith("|")]
    head = cells(lines[0])
    i_bw, i_tier, i_f = head.index("BW kHz"), head.index("tier"), head.index("filter")
    i_bias, i_iqr = head.index("mean signed bias m"), head.index("mean IQR m")
    val = {}
    for c in (cells(l) for l in lines[2:]):
        val[(c[i_bw], c[i_tier], c[i_f])] = (c[i_bias], c[i_iqr])
    bws, tiers = ("406.25", "1625"), ("static", "stop-and-go")
    filt = ("raw", "median-of-3")
    need = {(b, t, f) for b in bws for t in tiers for f in filt}
    if not need <= set(val):
        sys.exit(f"error: filters: rows missing in {FLT}: {sorted(need - set(val))}")
    src = {}
    L = [r"% GENERATED by tools/make_latex_tables.py from",
         f"%   {FLT.as_posix()} \"Aggregates per bandwidth x tier\" (columns "
         "\"mean signed bias m\" and \"mean IQR m\"). Do not edit by hand.",
         r"\begin{table}[t]", r"\centering",
         # 2026-11-10 (review edits): the caption states that the means use
         # unrounded per-marker values (Table tab:matched uses IQRs rounded to 0.1 m).
         r"\caption{Median-of-3 filter: mean signed error and mean IQR over ten "
         r"markers (22 August 2026), from unrounded per-marker values}",
         r"\label{tab:filters}",
         r"\footnotesize\setlength{\tabcolsep}{4pt}",
         r"\sisetup{retain-explicit-plus}",
         r"\begin{tabular}{@{}ll" + r"S[table-format=+2.2]" * 2 + "@{}}",
         r"\toprule",
         r"Bandwidth & Tier & {Raw} & {Median-of-3} \\",
         r"\midrule"]
    for k, (title, idx) in enumerate((("Mean signed error (m)", 0),
                                      ("Mean IQR (m)", 1))):
        if k:
            L.append(r"\addlinespace[3pt]")
        L.append(rf"\multicolumn{{4}}{{@{{}}l}}{{\textit{{{title}}}}} \\")
        for b in bws:
            for j, t in enumerate(tiers):
                vs = [val[(b, t, f)][idx] for f in filt]
                # The joined row is read back too, so a value in the wrong cell fails.
                src[(b, t, idx)] = (*vs, " & ".join(vs))
                lab = rf"{b}\,kHz" if j == 0 else ""
                L.append(rf"{lab} & {TIER_LABEL[t]} & " + " & ".join(vs) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(L), src


def readback(tex: str, src: dict, name: str) -> None:
    body = tex.replace("$", "")
    for key, vals in src.items():
        for v in vals:
            if v not in body:
                sys.exit(f"error: {name}: {key} value {v!r} missing after write")


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in (("matched.tex", matched), ("per_marker.tex", per_marker),
                     ("filters.tex", filters)):
        tex, src = fn()
        (OUT / name).write_text(tex, encoding="utf-8")
        readback((OUT / name).read_text(encoding="utf-8"), src, name)
        print(f"wrote {OUT / name} ({sum(len(v) for v in src.values())} values)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
