#!/usr/bin/env python3
"""Pack Pucks — LaTeX tables for the Part 1 paper, generated from data/analysis/.

Reads values as text from the analysis outputs and writes them into LaTeX
tables without recomputing or reformatting any number (only the sign is
wrapped in math mode). After writing, every value is read back from the
generated file and compared with its source; a mismatch aborts.

Outputs (paper/tables/):
  per_marker.tex  per-marker signed error, IQR, post-discard N and median
                  initiator RSSI for the four 22 Aug runs
                  <- data/analysis/2026-08-22_GMATownship_day2_tables_discard5s.md
                     TABLE 1
  matched.tex     Table I: MAE and mean signed error with 95 % bootstrap
                  intervals, the paired MAE ratio with its interval, and mean
                  IQR <- data/analysis/uncertainty.md section 1 and
                  data/analysis/aggregates.md "Accuracy and precision"
                  (added 2026-10-25)
  fit.tex         least-squares signed error vs distance, 406.25 kHz
                  <- data/analysis/aggregates.md, "Signed error vs distance";
                  95 % t-interval of the slope and the implied change over
                  270 m <- data/analysis/uncertainty.md section 2
  cycle.tex       cycle time per bandwidth: median, p05, p95, number of
                  intervals <- data/analysis/aggregates.md, cadence table
                  (p05 / p95 computed in aggregates.py since 2026-10-25)

Usage:
    python tools/make_latex_tables.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

AN = Path("data/analysis")
T5 = AN / "2026-08-22_GMATownship_day2_tables_discard5s.md"
AGG = AN / "aggregates.md"
UNC = AN / "uncertainty.md"
OUT = Path("paper/tables")

RUNS = ["406.25 kHz static", "406.25 kHz stop-and-go",
        "1625 kHz static", "1625 kHz stop-and-go"]
# Display labels: the hand-held tier is recorded with the stop-and-go
# procedure; the paper calls it the hand-held tier, and the source files
# keep their own labels.
TIER_LABEL = {"static": "static", "stop-and-go": "hand-held", "s&g": "hand-held"}


def cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def section(text: str, start: str) -> str:
    return text.split(start, 1)[1].split("\n## ", 1)[0]


def m(v: str) -> str:
    """Signed numbers in math mode; the digits are copied unchanged."""
    return f"${v}$" if v[:1] in "+-" else v


def per_marker() -> tuple[str, dict]:
    rows = [cells(l) for l in section(T5.read_text(encoding="utf-8"),
                                       "## TABLE 1").splitlines()
            if re.match(r"\|\s*\d+\s*\|", l)]
    # TABLE 1 columns per run: med, IQR, err, N, RSSI (5 each, after marker)
    src = {}
    L = [r"% GENERATED by tools/make_latex_tables.py from",
         f"%   {T5.as_posix()} TABLE 1. Do not edit by hand.",
         r"\begin{table*}[t]", r"\centering",
         r"\caption{Per-marker results, 22 August 2026: signed error $e_k$ and "
         r"IQR of the post-discard successful readings (m), post-discard "
         r"attempts $N_k$, and median Initiator RSSI (dBm).}",
         r"\label{tab:per-marker}",
         r"\setlength{\tabcolsep}{3pt}",
         r"\resizebox{\textwidth}{!}{%",
         r"\begin{tabular}{r" + "rrrr" * 4 + "}", r"\toprule",
         " & " + " & ".join(
             rf"\multicolumn{{4}}{{c}}"
             rf"{{{r.replace('stop-and-go', TIER_LABEL['stop-and-go'])}}}"
             for r in RUNS)
         + r" \\",
         " ".join(rf"\cmidrule(lr){{{2 + 4 * i}-{5 + 4 * i}}}" for i in range(4)),
         "Marker (m) & " + " & ".join([r"$e_k$ & IQR & $N_k$ & RSSI"] * 4)
         + r" \\", r"\midrule"]
    for c in rows:
        vals = []
        for i in range(4):
            med, iqr, err, n, rssi = c[1 + 5 * i: 6 + 5 * i]
            vals += [err, iqr, n, rssi]
            src[(c[0], RUNS[i])] = (err, iqr, n, rssi)
        L.append(c[0] + " & " + " & ".join(m(v) for v in vals) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}}", r"\end{table*}", ""]
    return "\n".join(L), src


def fit() -> tuple[str, dict]:
    sec = section(AGG.read_text(encoding="utf-8"),
                  "## Signed error vs distance, 406.25 kHz")
    rows = [cells(l) for l in sec.splitlines()
            if l.startswith("| static") or l.startswith("| stop-and-go")]
    usec = section(UNC.read_text(encoding="utf-8"),
                   "## 2. Slope of signed error vs distance")
    ci = {}
    for c in (cells(l) for l in usec.split("### Same intervals", 1)[0].splitlines()
              if l.startswith("| static") or l.startswith("| stop-and-go")):
        # tier, markers, n, df, slope, se, t, interval, implied change, has 0
        ci[(c[0], c[1])] = (c[3], c[4], c[7], c[8])
    src = {}
    L = [r"% GENERATED by tools/make_latex_tables.py from",
         f"%   {AGG.as_posix()}, \"Signed error vs distance, 406.25 kHz\", and",
         f"%   {UNC.as_posix()} section 2 (95 % t-interval, df = n - 2). "
         "Do not edit by hand.",
         r"\begin{table}[t]", r"\centering",
         r"\caption{Least-squares fit $e(d) = a + b\,d$ of the 406.25\,kHz "
         r"signed error against marker distance (22 August 2026), with the "
         r"95\,\% $t$-interval of $b$ ($n-2$ degrees of freedom) and the "
         r"change in error that interval allows over the 270\,m span of the "
         r"markers.}",
         r"\label{tab:fit}", r"\setlength{\tabcolsep}{3pt}",
         r"\resizebox{\columnwidth}{!}{%",
         r"\begin{tabular}{llrrrrrr}", r"\toprule",
         r"Tier & Markers & $n$ & $b$ (m/m) & s.e.\ of $b$ & 95\,\% interval "
         r"of $b$ & Over 270\,m (m) & $a$ (m) \\",
         r"\midrule"]
    for c in rows:
        tier, markers, n, slope, se, icpt = c[:6]
        df, slope_u, iv, span = ci[(tier, markers)]
        if slope_u != slope:
            sys.exit(f"error: fit {tier} {markers}: slope {slope} in AGG, "
                     f"{slope_u} in UNC")
        lo, hi = iv.split(" to ")
        slo, shi = span.split(" to ")
        src[(tier, markers)] = (n, slope, se, icpt, lo, hi, slo, shi)
        L.append(f"{TIER_LABEL[tier]} & {markers} & {n} & {m(slope)} & {se} & "
                 f"{m(lo)} to {m(hi)} & {m(slo)} to {m(shi)} & {m(icpt)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    return "\n".join(L), src


def matched() -> tuple[str, dict]:
    """Table I. MAE / mean signed error and their intervals from UNC
    section 1, point values cross-checked against AGG; mean IQR from AGG."""
    unc = UNC.read_text(encoding="utf-8")
    agg = AGG.read_text(encoding="utf-8")
    boot = {}
    for c in (cells(l) for l in section(unc, "## 1. Bootstrap").splitlines()
              if l.startswith("| static |") or l.startswith("| stop-and-go |")):
        if len(c) == 5:
            boot[(c[0], c[1], c[2])] = (c[3], *c[4].split(" to "))
        else:
            boot[(c[0], "ratio")] = (c[1].rstrip("×"),
                                     *(x.rstrip("×") for x in c[2].split(" to ")))

    def aggv(label: str, tier: str) -> str:
        line = next(l for l in agg.splitlines()
                    if l.startswith(f"| {label} | {tier} |"))
        return cells(line)[2].replace(" m", "").replace("×", "")

    tiers = (("static", "static", "Static"), ("stop-and-go", "s&g", "Hand-held"))
    src = {}
    L = [r"% GENERATED by tools/make_latex_tables.py from",
         f"%   {UNC.as_posix()} section 1 (MAE, mean signed error, MAE ratio, "
         "95 % bootstrap intervals) and",
         f"%   {AGG.as_posix()} \"Accuracy and precision\" (mean IQR; point "
         "values cross-checked). Do not edit by hand.",
         r"\begin{table}[t]", r"\centering",
         r"\caption{Accuracy and precision by bandwidth and tier (22 August "
         r"2026): means over the ten markers of the per-marker median error "
         r"and IQR, in metres. Brackets: 95\,\% percentile interval of a "
         r"bootstrap over markers (10\,000 resamples); the MAE ratio is "
         r"paired by marker.}",
         r"\label{tab:matched}",
         r"\small\setlength{\tabcolsep}{3pt}",
         r"\resizebox{\columnwidth}{!}{%",
         r"\begin{tabular}{llllr}", r"\toprule",
         r"Tier & Bandwidth & MAE & Mean signed error & Mean IQR \\",
         r"\midrule"]
    for i, (utier, atier, label) in enumerate(tiers):
        if i:
            L.append(r"\midrule")
        for bw in ("406.25 kHz", "1625 kHz"):
            mae = boot[(utier, "MAE", bw)]
            bias = boot[(utier, "mean signed error", bw)]
            iqr = aggv(f"Mean IQR, {bw}", atier)
            for name, got, want in (("MAE", mae[0], aggv(f"MAE, {bw}", atier)),
                                    ("bias", bias[0],
                                     aggv(f"Signed bias, {bw}", atier))):
                if got != want:
                    sys.exit(f"error: matched {utier} {bw} {name}: {got} in "
                             f"UNC, {want} in AGG")
            src[(utier, bw)] = (*mae, *bias, iqr)
            first = label if bw.startswith("406") else ""
            bwtex = bw.replace(" kHz", r"\,kHz")
            L.append(f"{first} & {bwtex} & {mae[0]} [{mae[1]}, {mae[2]}] & "
                     f"{m(bias[0])} [{m(bias[1])}, {m(bias[2])}] & {iqr} \\\\")
        r = boot[(utier, "ratio")]
        if r[0] != aggv("MAE ratio 406.25 / 1625", atier):
            sys.exit(f"error: matched {utier} ratio: {r[0]} in UNC")
        src[(utier, "ratio")] = r
        L.append(f" & MAE ratio & {r[0]}$\\times$ [{r[1]}, {r[2]}] & & \\\\")
    L += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    return "\n".join(L), src


def cycle() -> tuple[str, dict]:
    agg = AGG.read_text(encoding="utf-8")
    med = {}
    for bw in ("1625", "406.25"):
        line = next(l for l in agg.splitlines()
                    if l.startswith(f"| Cycle time, {bw} kHz (pooled median"))
        n = re.search(r"pooled median, (\d+) inter-row deltas", line).group(1)
        v = re.search(r"\| (\d+) ms \|", line).group(1)
        med[bw] = (v, n)
    pct = {}
    for bw in ("1625", "406.25"):
        line = next(l for l in agg.splitlines()
                    if l.startswith(f"| Cycle time p05 / p95, {bw} kHz"))
        p05, p95 = re.search(r"\| ([\d.]+) / ([\d.]+) ms \|", line).groups()
        pct[bw] = (p05, p95)
    src = {}
    L = [r"% GENERATED by tools/make_latex_tables.py from",
         f"%   {AGG.as_posix()} (cadence table: median, intervals, p05, p95). "
         "Do not edit by hand.",
         r"\begin{table}[t]", r"\centering",
         r"\caption{Cycle time per bandwidth: pooled inter-row intervals of "
         r"the 22 August Initiator files (ms).}",
         r"\label{tab:cycle}", r"\setlength{\tabcolsep}{4pt}",
         r"\begin{tabular}{lrrrr}", r"\toprule",
         r"Bandwidth & Median & p05 & p95 & Intervals \\", r"\midrule"]
    for bw in ("1625", "406.25"):
        v, n = med[bw]
        p05, p95 = pct[bw]
        src[bw] = (v, p05, p95, n)
        L.append(rf"{bw}\,kHz & {v} & {p05} & {p95} & {n} \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(L), src


def readback(tex: str, src: dict, name: str) -> None:
    body = tex.replace("$", "")
    for key, vals in src.items():
        for v in vals:
            if v not in body:
                sys.exit(f"error: {name}: {key} value {v!r} missing after write")


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in (("matched.tex", matched), ("per_marker.tex", per_marker),
                     ("fit.tex", fit),
                     ("cycle.tex", cycle)):
        tex, src = fn()
        (OUT / name).write_text(tex, encoding="utf-8")
        readback((OUT / name).read_text(encoding="utf-8"), src, name)
        print(f"wrote {OUT / name} ({sum(len(v) for v in src.values())} values)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
